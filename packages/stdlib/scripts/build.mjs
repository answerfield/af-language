// Writes out/index.js with the text of std.af, so Node, web workers and bundled extensions load std without file
// access. No dependencies.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const std = readFileSync(join(root, 'std.af'), 'utf8');

const header = '// Generated by scripts/build.mjs, do not edit by hand.\n\n';
mkdirSync(join(root, 'out'), { recursive: true });
writeFileSync(join(root, 'out/index.js'), `${header}export const STD = ${JSON.stringify(std)};\n`);
writeFileSync(join(root, 'out/index.d.ts'), `${header}/** Text of std.af. */\nexport declare const STD: string;\n`);
console.log('std.af → out/index.js');
