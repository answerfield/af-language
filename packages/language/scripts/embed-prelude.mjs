// Embeds prelude.af as a string, so Node and web workers can load it without file access.
// std.af is not embedded: it comes from the package @answerfield/stdlib at runtime (src/builtin/builtins.ts).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const prelude = readFileSync(join(here, '../src/builtin/prelude.af'), 'utf8');
const out = join(here, '../src/builtin/prelude.generated.ts');

writeFileSync(out, `// Generated by scripts/embed-prelude.mjs, do not edit by hand.

/** Text of prelude.af. */
export const PRELUDE: string = ${JSON.stringify(prelude)};
`);
console.log('prelude.af → src/builtin/prelude.generated.ts');
